// Автогенерация SKU
function generateSku(category) {
    if (!category) return '';
    
    // Первые 2 буквы (или символа) категории
    const prefix = category.substring(0, 2).toUpperCase();
    return prefix;
}

// Получение следующего ID для SKU
async function getNextSkuId() {
    try {
        const products = await getAllItems('products');
        const maxId = products.reduce((max, p) => Math.max(max, p.id || 0), 0);
        return maxId + 1;
    } catch (error) {
        console.error('Error getting next SKU ID:', error);
        return 1;
    }
}

// === ЗАГРУЗКА ДАННЫХ ===
async function loadProducts() {
    console.log('🚀 loadProducts started');
    
    const tbody = document.querySelector('#productTable tbody');
    if (tbody) {
        console.log('✅ Found tbody');
        tbody.innerHTML = '<tr><td colspan="7" style="text-align: center; padding: 20px;">⏳ Загрузка...</td></tr>';
    } else {
        console.error('❌ tbody not found!');
        return;
    }
    
    try {
        console.log('📦 Loading products from database...');
        let products = await getAllItems('products');
        
        console.log(`📊 Raw products from DB:`, products);
        console.log(`📊 Total products: ${products.length}`);
        
        // Применяем фильтры
        if (currentFilters.category) {
            products = products.filter(p => p.category === currentFilters.category);
        }
        if (currentFilters.name) {
            const search = currentFilters.name.toLowerCase();
            products = products.filter(p => 
                (p.name && p.name.toLowerCase().includes(search)) || 
                (p.sku && p.sku.toLowerCase().includes(search))
            );
        }
        if (currentFilters.status) {
            products = products.filter(p => p.is_active === (currentFilters.status === 'active'));
        }
        
        console.log(`📊 Products after filters: ${products.length}`);
        
        // Сортировка
        products.sort((a, b) => (b.id || 0) - (a.id || 0));
        
        // Пагинация
        const total = products.length;
        const start = (currentPage - 1) * currentPageSize;
        const pagedProducts = products.slice(start, start + currentPageSize);
        
        console.log(`📊 Paged products: ${pagedProducts.length}, page: ${currentPage}`);
        console.log('🎨 Calling renderTable...');
        
        renderTable(pagedProducts);
        
        console.log('📄 Calculating pagination...');
        const totalPages = Math.ceil(total / currentPageSize);
        
        const paginationEl = document.getElementById('pagination');
        const paginationInfoEl = document.getElementById('paginationInfo');
        
        console.log('📍 Pagination elements:', paginationEl, paginationInfoEl);
        
        if (paginationEl && paginationInfoEl) {
            renderPagination(
                paginationEl,
                paginationInfoEl,
                currentPage,
                totalPages,
                total,
                currentPageSize,
                goToPage
            );
            console.log('✅ Pagination rendered');
        } else {
            console.warn('⚠️ Pagination elements not found');
        }
        
        console.log('✅ loadProducts completed successfully');
        
    } catch (error) {
        console.error('❌ Error in loadProducts:', error);
        console.error('Stack:', error.stack);
        
        if (tbody) {
            tbody.innerHTML = `<tr><td colspan="7" style="text-align: center; color: #ef4444;">❌ Ошибка: ${error.message}</td></tr>`;
        }
    }
}

function renderTable(products) {
    console.log('🎨 renderTable called with:', products);
    
    const shouldAnimate = getSetting('ui.animateRows');
    const tbody = document.querySelector('#productTable tbody');
    
    // Получаем текущий порог
    const lowStockThreshold = parseInt(document.getElementById('lowStockThreshold')?.value) || 10;
    
    if (!tbody) {
        console.error('❌ Table body not found!');
        return;
    }
    
    if (!products || products.length === 0) {
        console.log('⚠️ No products to render');
        tbody.innerHTML = '<tr><td colspan="7" style="text-align: center; padding: 40px; color: #94a3b8;"> Нет товаров. Добавьте первый товар!</td></tr>';
        return;
    }
    
    try {
        tbody.innerHTML = products.map((product, index) => {
            console.log('📦 Rendering product:', product);
            
            const animClass = shouldAnimate ? 'table-row-animate' : '';
            const animDelay = shouldAnimate ? `style="animation-delay: ${index * 0.04}s;"` : '';
            
            const statusClass = product.is_active ? 'badge-active' : 'badge-inactive';
            const statusText = product.is_active ? 'В продаже' : 'Снят';
            
            // Проверка на null/undefined значения
            const sku = product.sku || 'N/A';
            const category = product.category || 'Без категории';
            const name = product.name || 'Без названия';
            const price = parseFloat(product.price) || 0;
            const quantity = parseInt(product.quantity) || 0;
            
            // Проверка на низкий остаток
            const isLowStock = quantity < lowStockThreshold;
            const stockCellStyle = isLowStock 
                ? 'text-align: center; background: #fef3c7; color: #d97706; font-weight: 600; border-radius: 4px; padding: 2px 8px;' 
                : 'text-align: center;';
            
            return `
            <tr data-id="${product.id}" 
                class="${animClass}" 
                ${animDelay}
                onclick="handleRowClick(event, ${product.id})">
                <td><strong>${sku}</strong></td>
                <td>${category}</td>
                <td>${name}</td>
                <td style="text-align: right;">${price.toFixed(2)} ₽</td>
                <td style="${stockCellStyle}">${quantity}</td>
                <td><span class="badge ${statusClass}">${statusText}</span></td>
            </tr>`; 
        }).join('');
        
        console.log('✅ Table rendered successfully');
        
    } catch (error) {
        console.error('❌ Error rendering table:', error);
        tbody.innerHTML = `<tr><td colspan="7" style="text-align: center; color: #ef4444;">❌ Ошибка рендеринга</td></tr>`;
    }
}

window.goToPage = function(newPage) {
    currentPage = newPage;
    loadProducts();
};

// === ВЫДЕЛЕНИЕ СТРОК ===
window.handleRowClick = function(event, id) {
    event.preventDefault();
    const row = event.currentTarget;
    const modifier = getSetting('ui.selectionModifier') || 'shift';
    const isModifier = modifier === 'shift' ? event.shiftKey : (event.ctrlKey || event.metaKey);

    if (isModifier) {
        if (selectedRows.has(id)) selectedRows.delete(id);
        else selectedRows.set(id, row);
    } else {
        selectedRows.clear();
        selectedRows.set(id, row);
    }
    updateSelectionUI();
};

window.updateSelectionUI = function() {
    document.querySelectorAll('.crm-table tbody tr').forEach(tr => tr.classList.remove('selected'));
    selectedRows.forEach(row => row.classList.add('selected'));

    const bar = document.getElementById('bulkActionBar');
    const countBadge = document.getElementById('selectedCount');
    const btnEdit = document.getElementById('btnBulkEdit');
    const btnDelete = document.getElementById('btnBulkDelete');
    const count = selectedRows.size;

    if (count > 0) {
        bar.classList.add('visible');
        countBadge.textContent = count;
        btnEdit.disabled = count !== 1;
        btnDelete.disabled = false;
    } else {
        bar.classList.remove('visible');
    }
};

window.clearSelection = function() {
    selectedRows.clear();
    updateSelectionUI();
};

