// === РЕДАКТИРОВАНИЕ И УДАЛЕНИЕ ===
window.openEditProduct = async function(id) {
    try {
        const products = await getAllItems('products');
        const product = products.find(p => p.id === id);
        if (!product) { showToast('❌ Товар не найден'); return; }
        
        document.getElementById('editProductId').value = product.id;
        document.getElementById('editProductSku').value = product.sku; 
        document.getElementById('editProductSku').removeAttribute('readonly'); 
        document.getElementById('editProductCategory').value = product.category;
        document.getElementById('editProductName').value = product.name;
        document.getElementById('editProductDescription').value = product.description || '';
        document.getElementById('editProductPrice').value = product.price;
        document.getElementById('editProductQuantity').value = product.quantity;
        document.getElementById('editProductStatus').value = product.is_active ? 'active' : 'inactive';
        
        openModal('editProductModal');
    } catch (err) {
        showToast('❌ Ошибка: ' + err.message);
    }
};

window.deleteProduct = async function(id) {
    if (!confirm('Удалить этот товар?')) return;
    
    try {
        await deleteItem('products', id);
        if (window.saveDataToFile) await window.saveDataToFile();
        showToast('✅ Товар удален');
        loadProducts();
    } catch (err) {
        showToast('❌ Ошибка: ' + err.message);
    }
};

window.editSelected = async function() {
    if (selectedRows.size !== 1) return;
    const [id] = selectedRows.keys();
    await openEditProduct(id);
};

window.deleteSelected = async function() {
    const count = selectedRows.size;
    if (count === 0) return;
    if (!confirm(`Удалить ${count} товаров?`)) return;

    try {
        for (const id of Array.from(selectedRows.keys())) {
            await deleteItem('products', id);
        }
        if (window.saveDataToFile) await window.saveDataToFile();
        window.clearSelection();
        showToast(`✅ Удалено товаров: ${count}`);
        loadProducts();
    } catch (err) {
        showToast('❌ Ошибка: ' + err.message);
    }
};

// === ОБРАБОТЧИКИ СОБЫТИЙ ===
function setupEventListeners() {
    // Форма создания
    document.getElementById('createProductForm').addEventListener('submit', async (e) => {
        e.preventDefault();
        await handleCreateProduct();
    });

    // Обработчик изменения порога низкого остатка
    const thresholdInput = document.getElementById('lowStockThreshold');
    if (thresholdInput) {
        thresholdInput.addEventListener('change', async (e) => {
            const newValue = parseInt(e.target.value);
            if (!isNaN(newValue) && newValue >= 0) {
                // Сохраняем в настройки
                const { updateSetting } = await import('./settings-manager.js');
                await updateSetting('inventory.lowStockThreshold', newValue);
                
                // Перерисовываем таблицу с новым порогом
                loadProducts();
                
                // Показываем уведомление
                showToast(`✅ Порог низкого остатка установлен: ${newValue}`);
            }
        });
        
        // Также обновляем при вводе (без сохранения, только предпросмотр)
        thresholdInput.addEventListener('input', () => {
            loadProducts();
        });
    }

    // Автогенерация SKU при изменении категории (в режиме создания)
    const createCategory = document.getElementById('productCategory');
    if (createCategory) {
        createCategory.addEventListener('input', async (e) => {
            const category = e.target.value;
            if (category) {
                const prefix = generateSku(category);
                const nextId = await getNextSkuId();
                const generatedSku = `${prefix}-${nextId}`;
                
                // Показываем превью (опционально)
                console.log(`📦 Будет сгенерирован SKU: ${generatedSku}`);
            }
        });
    }    
    // Форма редактирования
    document.getElementById('editProductForm').addEventListener('submit', async (e) => {
        e.preventDefault();
        await handleEditProduct();
    });
    
    // Фильтры
    document.getElementById('btnApplyFilters').addEventListener('click', () => {
        currentFilters = {
            category: document.getElementById('filterCategory').value || null,
            name: document.getElementById('filterName').value || null,
            status: document.getElementById('filterStatus').value || null
        };
        currentPage = 1;
        loadProducts();
    });
    
    document.getElementById('btnResetFilters').addEventListener('click', () => {
        document.getElementById('filterCategory').value = '';
        document.getElementById('filterName').value = '';
        document.getElementById('filterStatus').value = '';
        currentFilters = {};
        currentPage = 1;
        loadProducts();
        populateCategoryFilter();
    });
    
    // Пагинация
    document.getElementById('pageSize').addEventListener('change', (e) => {
        currentPageSize = parseInt(e.target.value);
        currentPage = 1;
        loadProducts();
    });
}

async function handleCreateProduct() {
    const category = document.getElementById('productCategory').value;
    
    // Генерируем SKU автоматически
    const skuPrefix = generateSku(category);
    const nextId = await getNextSkuId();
    const finalSku = `${skuPrefix}-${nextId}`;
    
    const formData = {
        sku: finalSku, 
        category: category,
        name: document.getElementById('productName').value,
        description: document.getElementById('productDescription').value,
        price: parseFloat(document.getElementById('productPrice').value),
        quantity: parseInt(document.getElementById('productQuantity').value),
        is_active: document.getElementById('productStatus').value === 'active',
        created_at: new Date().toISOString()
    };
    
    try {
        await addItem('products', formData);
        if (window.saveDataToFile) await window.saveDataToFile();
        
        showToast(`✅ Товар добавлен (SKU: ${finalSku})`);
        document.getElementById('createProductForm').reset();
        closeModal('createProductModal');
        loadProducts();
        populateCategoryDropdowns(); // Обновляем список категорий
    } catch (error) {
        showToast('❌ Ошибка: ' + error.message);
    }
}

async function handleEditProduct() {
    const id = parseInt(document.getElementById('editProductId').value);
    const updates = {
        sku: document.getElementById('editProductSku').value.toUpperCase(), //  Можно изменить
        category: document.getElementById('editProductCategory').value,
        name: document.getElementById('editProductName').value,
        description: document.getElementById('editProductDescription').value,
        price: parseFloat(document.getElementById('editProductPrice').value),
        quantity: parseInt(document.getElementById('editProductQuantity').value),
        is_active: document.getElementById('editProductStatus').value === 'active',
        updated_at: new Date().toISOString()
    };
    
    try {
        await updateItem('products', id, updates);
        if (window.saveDataToFile) await window.saveDataToFile();
        
        showToast('✅ Товар обновлен');
        closeModal('editProductModal');
        loadProducts();
        populateCategoryDropdowns();
    } catch (error) {
        showToast('❌ Ошибка: ' + error.message);
    }
}

// === ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ ===
function showToast(message) {
    const toast = document.createElement('div');
    toast.className = 'toast';
    toast.textContent = message;
    toast.style.cssText = 'position: fixed; bottom: 20px; right: 20px; background: #333; color: white; padding: 12px 20px; border-radius: 8px; z-index: 9999; animation: fadeIn 0.3s;';
    document.body.appendChild(toast);
    setTimeout(() => toast.remove(), 3000);
}

window.openModal = function(modalId) {
    document.getElementById(modalId).classList.add('active');
    document.body.style.overflow = 'hidden';
};

window.closeModal = function(modalId) {
    document.getElementById(modalId).classList.remove('active');
    document.body.style.overflow = '';
};

window.closeModalOnOverlay = function(event, modalId) {
    if (event.target.id === modalId) {
        window.closeModal(modalId);
    }
};

